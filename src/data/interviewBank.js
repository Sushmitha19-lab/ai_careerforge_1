export const QUESTIONS = [...CORE_QUESTIONS, ...extraQuestions(row)];

const byId = Object.fromEntries(QUESTIONS.map((item) => [item.id, item]));

export function getQuestionById(id) {
  return byId[id] || null;
}

export function questionsFor(track, roundId) {
  return QUESTIONS.filter(
    (item) => item.track === track && item.round === roundId
  );
}

function pickOne(list) {
  if (!list.length) {
    return null;
  }
  return list[Math.floor(Math.random() * list.length)];
}

export function pickForRound(track, roundId, preferredLevel, askedIds) {
  const asked = askedIds instanceof Set ? askedIds : new Set(askedIds || []);
  const pool = questionsFor(track, roundId).filter((item) => !asked.has(item.id));
  const order = LEVEL_ORDER[preferredLevel] || LEVEL_ORDER.foundation;

  for (const level of order) {
    const hit = pickOne(pool.filter((item) => item.level === level));
    if (hit) {
      return hit;
    }
  }

  return pool[0] || null;
}

export function pickRoundSet(track, roundId, count, askedIds, preferredLevel) {
  const asked = new Set(askedIds || []);
  const picked = [];
  for (let i = 0; i < count; i += 1) {
    const question = pickForRound(track, roundId, preferredLevel, asked);
    if (!question) {
      break;
    }
    asked.add(question.id);
    picked.push(question);
  }
  return picked;
}
