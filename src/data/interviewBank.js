function row(id, track, round, level, prompt, keys, patternIds) {
  return {
    id,
    track,
    round,
    topic: round,
    level,
    type: round,
    prompt,
    keywords: keys.map(([label, ...terms]) =>
      k(label, terms.length ? terms : [label])
    ),
    patterns: (patternIds || ["definition", "steps"]).map((name) => P[name]),
    followUps: { strong: [], gaps: {} },
  };
}

